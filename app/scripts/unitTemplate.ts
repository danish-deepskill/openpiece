/**
 * Generates the ARTIST TEMPLATE (docs/art/unit-template.svg) from the live anatomy contract —
 * `npm run art:template`. The SVG is computed from the SAME exported constants the renderer uses
 * (ANATOMY / SLOT_ANCHOR / BODY_FRAME_R / restHand), so retuning proportions and re-running keeps the
 * template truthful by construction: artists always trace what the game actually draws.
 *
 * Conventions on the sheet (mirrored in docs/art/README.md): square canvas = the 'body' authoring frame
 * (±BODY_FRAME_R·r around the body center), FORWARD = UP, body center = canvas center.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { HAND_R_FRAC, restHand } from '../src/combat/swing';
import { ANATOMY, BODY_FRAME_R, SLOT_ANCHOR } from '../src/draw/actorDraws';
import { Bodies } from '../src/defs/bodies';

const SIZE = 512; // px — the reference canvas artists duplicate (any square multiple works)
const C = SIZE / 2;
const R = SIZE / (2 * BODY_FRAME_R); // body collision radius in template px

const hex = (c: number): string => '#' + c.toString(16).padStart(6, '0');
const OUTLINE = hex(0x4d4a45);
const SKIN = hex(Bodies.grunt.baseColor);
const GARB = hex(Bodies.grunt.garb ?? 0x6b4a3a);

// facing UP: forward f (×r) → −y; sideways s (×r) → +x
const px = (s: number): number => C + s * R;
const py = (f: number): number => C - f * R;

const A = ANATOMY;
const widestFrac = A.shoulderOut + A.shoulderHalfW;
const parts: string[] = [];

// canvas + frame
parts.push(`<rect x="0" y="0" width="${SIZE}" height="${SIZE}" fill="#2e3630"/>`);
parts.push(`<rect x="1" y="1" width="${SIZE - 2}" height="${SIZE - 2}" fill="none" stroke="#889" stroke-width="2" stroke-dasharray="8 6"/>`);

// reference rings: the COLLISION circle (r — the actual hitbox) and the widest-silhouette ring
parts.push(`<circle cx="${C}" cy="${C}" r="${R}" fill="none" stroke="#e06c5a" stroke-width="1.5" stroke-dasharray="6 5"/>`);
parts.push(`<circle cx="${C}" cy="${C}" r="${widestFrac * R}" fill="none" stroke="#8aa" stroke-width="1" stroke-dasharray="3 5"/>`);

// center registration cross
parts.push(`<line x1="${C - 14}" y1="${C}" x2="${C + 14}" y2="${C}" stroke="#e6e6e6" stroke-width="1"/>`);
parts.push(`<line x1="${C}" y1="${C - 14}" x2="${C}" y2="${C + 14}" stroke="#e6e6e6" stroke-width="1"/>`);

// ----- the mannequin, exactly as drawActor paints it (facing UP on this sheet, no swing twist) -----
// Perspective model: head sits AWAY from facing (low on this sheet), body/arms on the facing side (high).
// In game a unit walking SOUTH (toward the camera) shows this pose flipped — the base sketch's look.
// sleeves + rest fists FIRST (dashed — they ANIMATE with swings; wearables must never depend on them)
for (const s of [-1, 1] as const) {
  const [hx, hy] = restHand(-Math.PI / 2, s, R); // the REAL rest-hand fn — forward = up
  const sx = px(s * A.shoulderOut);
  const sy = py(A.shoulderFwd);
  parts.push(`<line x1="${sx}" y1="${sy}" x2="${C + hx}" y2="${C + hy}" stroke="${GARB}" stroke-width="${A.armW * R}" stroke-linecap="round" stroke-dasharray="8 6"/>`);
  parts.push(`<circle cx="${C + hx}" cy="${C + hy}" r="${R * HAND_R_FRAC}" fill="${SKIN}" stroke="${OUTLINE}" stroke-width="2" stroke-dasharray="4 3"/>`);
}
// torso + shoulder slabs: each part with its OWN outline (segments, not a fused garment) — same as in-game
const torsoY = py(A.torsoFwd);
parts.push(`<ellipse cx="${C}" cy="${torsoY}" rx="${A.torsoHalfW * R}" ry="${A.torsoHalfL * R}" fill="${GARB}" stroke="${OUTLINE}" stroke-width="2"/>`);
for (const s of [-1, 1]) {
  parts.push(`<ellipse cx="${px(s * A.shoulderOut)}" cy="${py(A.shoulderFwd)}" rx="${A.shoulderHalfW * R}" ry="${A.shoulderHalfL * R}" fill="${GARB}" stroke="${OUTLINE}" stroke-width="2"/>`);
}
// head — skin, offset away from the aim
parts.push(`<circle cx="${C}" cy="${py(-A.headBack)}" r="${A.headR * R}" fill="${SKIN}" stroke="${OUTLINE}" stroke-width="2"/>`);

// ----- slot anchors: crosshair + label at each 'item'-frame pin point -----
const anchors = Object.entries(SLOT_ANCHOR) as Array<[string, number]>;
for (const [slot, f] of anchors) {
  const y = py(f);
  parts.push(`<line x1="${C - 10}" y1="${y}" x2="${C + 10}" y2="${y}" stroke="#ffd24a" stroke-width="1.5"/>`);
  parts.push(`<line x1="${C}" y1="${y - 10}" x2="${C}" y2="${y + 10}" stroke="#ffd24a" stroke-width="1.5"/>`);
  parts.push(`<text x="${C + 16}" y="${y + 4}" fill="#ffd24a" font-family="monospace" font-size="13">${slot} (${f >= 0 ? '+' : ''}${f.toFixed(2)}r)</text>`);
}

// ----- legend -----
const legend = [
  `unit-template — GENERATED by 'npm run art:template', do not hand-edit`,
  `square canvas = the 'body' sprite frame: ±${BODY_FRAME_R}r, body center = canvas center, FORWARD = UP`,
  `red dashed ring = the collision circle r (THE hitbox — art may overhang, gameplay reads this)`,
  `head r=${A.headR}r @ -${A.headBack}r (away from facing) · torso ${A.torsoHalfW}×${A.torsoHalfL}r @ +${A.torsoFwd}r · shoulders ${A.shoulderHalfW}×${A.shoulderHalfL}r @ ±${A.shoulderOut}r`,
  `outline ${OUTLINE} 2px · flat fills, max 2 values per material · chest sprites: transparent head cutout`,
];
legend.forEach((line, i) => {
  parts.push(`<text x="10" y="${SIZE - 10 - (legend.length - 1 - i) * 16}" fill="#cfd4d8" font-family="monospace" font-size="11">${line}</text>`);
});

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}" viewBox="0 0 ${SIZE} ${SIZE}">\n${parts.join('\n')}\n</svg>\n`;

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, '..', '..', 'docs', 'art');
mkdirSync(outDir, { recursive: true });
const out = join(outDir, 'unit-template.svg');
writeFileSync(out, svg);
console.log(`wrote ${out} (r = ${R.toFixed(1)}px on a ${SIZE}px canvas)`);
